/**
 * Purpose: generate a type-only stub for @prisma/client from schema.prisma so
 * `tsc --noEmit` can verify the repo in an environment where Prisma's engine
 * binaries cannot be downloaded (a sandboxed CI runner, an offline machine).
 *
 * This is a VERIFICATION AID, never part of the runtime. The real client comes
 * from `pnpm db:generate`, and tsconfig.json does not reference this file;
 * only tsconfig.verify.json does.
 *
 * Scalars are typed exactly, so a misspelled column is still a compile error.
 * Relation fields are typed loosely, because reproducing Prisma's conditional
 * include/select types here would be a second implementation of Prisma and
 * would produce false positives rather than finding real bugs.
 *
 * Usage: node scripts/make-prisma-typestub.mjs
 */

import { readFileSync, mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..");
const schemaPath = join(root, "packages/core/prisma/schema.prisma");
const outPath = join(root, "packages/core/types/prisma-client-stub.d.ts");

const SCALARS = {
	String: "string",
	Boolean: "boolean",
	Int: "number",
	BigInt: "bigint",
	Float: "number",
	Decimal: "number",
	DateTime: "Date",
	Json: "unknown",
	Bytes: "Uint8Array",
};

const schema = readFileSync(schemaPath, "utf8");

/** Strip comments so a `///` doc line cannot be mistaken for a field. */
const lines = schema
	.split("\n")
	.map((line) => line.replace(/\/\/.*$/, "").trimEnd())
	.filter((line) => line.trim() !== "");

const models = [];
let current;

for (const line of lines) {
	const modelStart = /^model\s+(\w+)\s*\{/.exec(line.trim());
	if (modelStart) {
		current = { name: modelStart[1], scalars: [], relations: [] };
		models.push(current);
		continue;
	}
	if (!current) continue;
	if (line.trim() === "}") {
		current = undefined;
		continue;
	}
	if (line.trim().startsWith("@@")) continue;

	const field = /^\s*(\w+)\s+(\w+)(\[\])?(\?)?/.exec(line);
	if (!field) continue;
	const [, name, type, list, optional] = field;
	const scalar = SCALARS[type];
	if (scalar) {
		const tsType = list ? `${scalar}[]` : scalar;
		current.scalars.push({ name, tsType, optional: Boolean(optional) });
	} else {
		current.relations.push({ name, type, list: Boolean(list), optional: Boolean(optional) });
	}
}

const modelTypes = models
	.map((model) => {
		// Nullable scalars are `T | null` and still required, matching what Prisma
		// actually generates. Marking them optional would inject `undefined` into
		// every consumer and produce a wall of false positives.
		const scalarLines = model.scalars.map(
			({ name, tsType, optional }) => `\t${name}: ${tsType}${optional ? " | null" : ""};`,
		);
		// Relations are typed but always present. Prisma only materialises them on
		// include; making them required here is deliberately more permissive, so
		// the stub never invents an error a real client would not raise.
		const relationLines = model.relations.map(
			({ name, type, list, optional }) =>
				`\t${name}: ${type}${list ? "[]" : optional ? " | null" : ""};`,
		);
		return [
			`export type ${model.name} = {`,
			...scalarLines,
			...relationLines,
			"\t_count?: any;",
			"};",
		].join("\n");
	})
	.join("\n\n");

const delegates = models
	.map((model) => {
		const t = model.name;
		return `\t${t.charAt(0).toLowerCase() + t.slice(1)}: Delegate<${t}>;`;
	})
	.join("\n");

const out = `/* AUTOGENERATED by scripts/make-prisma-typestub.mjs. Do not edit.
 * Type-only stand-in for the generated Prisma client, used by
 * tsconfig.verify.json when engine binaries are unavailable. Not runtime code.
 */

${modelTypes}

type Delegate<T> = {
	findMany(args?: any): Promise<T[]>;
	findUnique(args: any): Promise<T | null>;
	findUniqueOrThrow(args: any): Promise<T>;
	findFirst(args?: any): Promise<T | null>;
	create(args: any): Promise<T>;
	createMany(args: any): Promise<{ count: number }>;
	update(args: any): Promise<T>;
	updateMany(args: any): Promise<{ count: number }>;
	upsert(args: any): Promise<T>;
	delete(args: any): Promise<T>;
	deleteMany(args?: any): Promise<{ count: number }>;
	count(args?: any): Promise<number>;
	aggregate(args?: any): Promise<any>;
	groupBy(args?: any): Promise<any[]>;
};

export declare class PrismaClient {
	constructor(options?: any);
${delegates}
	$connect(): Promise<void>;
	$disconnect(): Promise<void>;
	$transaction<R>(fn: (tx: PrismaClient) => Promise<R>): Promise<R>;
	$queryRaw<T = unknown>(query: TemplateStringsArray, ...values: unknown[]): Promise<T>;
	$executeRaw(query: TemplateStringsArray, ...values: unknown[]): Promise<number>;
}

export declare namespace Prisma {
	type JsonValue = string | number | boolean | null | JsonValue[] | { [k: string]: JsonValue };
	type InputJsonValue = JsonValue;
	class PrismaClientKnownRequestError extends Error {
		code: string;
		meta?: Record<string, unknown>;
	}
	class PrismaClientValidationError extends Error {}
}

export default PrismaClient;
`;

mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(outPath, out, "utf8");
console.log(`wrote ${outPath} (${models.length} models: ${models.map((m) => m.name).join(", ")})`);
